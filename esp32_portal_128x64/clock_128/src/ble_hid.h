#pragma once
#include <stdint.h>

// BLE HID host: connects to a BLE keyboard / remote / air-mouse and reports its input as events.
// NOTE: the ESP32-S3 only has Bluetooth LE, Bluetooth "Classic" HID devices can't be used.

// keyboard usages (HID page 7).
// keys of other device types (consumer menu keys, d-pad, mouse button) are translated to these
enum HidKey : uint16_t {
    HID_KEY_ENTER = 0x28,
    HID_KEY_ESC = 0x29,
    HID_KEY_BACKSPACE = 0x2A,
    HID_KEY_TAB = 0x2B,
    HID_KEY_CAPS_LOCK = 0x39,
    HID_KEY_MENU = 0x65,  // the application / context menu key
    HID_KEY_HOME = 0x4A,
    HID_KEY_PGUP = 0x4B,
    HID_KEY_DELETE = 0x4C,
    HID_KEY_END = 0x4D,
    HID_KEY_PGDN = 0x4E,
    HID_KEY_RIGHT = 0x4F,
    HID_KEY_LEFT = 0x50,
    HID_KEY_DOWN = 0x51,
    HID_KEY_UP = 0x52,
    HID_KEY_VOL_UP = 0x80,
    HID_KEY_VOL_DOWN = 0x81,
    HID_KEY_BACK = 0x1000, // no keyboard equivalent, the consumer page Back key (remotes)
    HID_KEY_POWER = 0x1001, // SysPowerDown, or a Power key
    HID_KEY_REMOTE_HOME = 0x1002, // the consumer page Home key of remotes, not the keyboard's Home
};

struct HidEvent {
    enum Type : uint8_t { KEY_DOWN, KEY_UP, MOVE };
    Type type = KEY_DOWN;
    bool repeat = false;  // KEY_DOWN generated by auto-repeat of a held key
    uint16_t key = 0;     // keyboard usage (HidKey or other page 7 usage), 0 if the input has no keyboard equivalent
    uint32_t usage = 0;   // the original (page << 16) | usage
    char ch = 0;          // printable character of a KEY_DOWN, 0 if none
    int16_t dx = 0, dy = 0; // MOVE, relative
};

// starts BLE and a background task that scans, connects and reconnects to the first HID device found
void ble_hid_begin();

// gets the next input event, call from loop(). returns false if there's none
bool ble_hid_poll(HidEvent& ev);

// the last key pressed or released as text, like the serial log ("000c:0224 Back").
// count changes with every new one, pressed says if it was pressed or released
const char* ble_hid_last_key(uint32_t* count = nullptr, bool* pressed = nullptr);

// the name of the connected device, empty when none is connected
const char* ble_hid_device();

// caps lock state, the typed chars (HidEvent::ch) already take it into account
bool ble_hid_caps_lock();
